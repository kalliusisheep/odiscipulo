const ALL_BIBLICAL_CHARACTERS = [...RAW_BIBLICAL_CHARACTERS, ...ADDITIONAL_BIBLICAL_CHARACTERS, ...CATALOG_BIBLICAL_CHARACTERS];

const isValidBiblicalCharacter = (character: BiblicalCharacter) => {
  const hints = character.hints.map((hint) => hint.trim()).filter(Boolean);
  return Boolean(character.id.trim() && character.name.trim() && character.summary.trim() && character.references.length > 0)
    && hints.length === 4
    && new Set([character.name, ...character.aliases]).size === character.aliases.length + 1;
};

export const BIBLICAL_CHARACTERS = ALL_BIBLICAL_CHARACTERS.filter(isValidBiblicalCharacter);

export const normalizeGameAnswer = (value: string) =>
  value.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase().replace(/[^a-z0-9]+/g, "").trim();

export const isCorrectCharacterAnswer = (character: BiblicalCharacter, answer: string) => {
  const normalized = normalizeGameAnswer(answer);
  return [character.name, ...character.aliases].some((item) => normalizeGameAnswer(item) === normalized);
};
