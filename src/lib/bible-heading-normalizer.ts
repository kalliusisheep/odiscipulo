const HEADING_REPLACEMENTS = new Map(
  Object.entries(HEADING_WORD_REPLACEMENTS).map(([source, replacement]) => [
    source.normalize("NFC").replace(/'/g, "’").toLocaleLowerCase("pt-BR"),
    replacement,
  ]),
);

function preserveHeadingCase(source: string, replacement: string): string {
  if (!replacement || !source) return replacement;
  const startsUppercase =
    source[0] === source[0].toLocaleUpperCase("pt-BR") &&
    source[0] !== source[0].toLocaleLowerCase("pt-BR");
  return startsUppercase
    ? replacement[0].toLocaleUpperCase("pt-BR") + replacement.slice(1)
    : replacement;
}

export function normalizeBibleSectionHeading(value?: string): string | undefined {
  if (!value) return undefined;
  const normalized = value
    .normalize("NFC")
    .replace(/'/g, "’")
    .replace(/\s*\[[A-Z]{3}\]/g, "")
    .replace(/\s+/g, " ")
    .trim();

  return normalized
    .replace(/[A-Za-zÀ-ÿ’']+/g, (token) => {
      const replacement = HEADING_REPLACEMENTS.get(token.toLocaleLowerCase("pt-BR"));
      return replacement === undefined ? token : preserveHeadingCase(token, replacement);
    })
    .replace(/\s+([.,;:!?])/g, "$1")
    .replace(/\(\s+/g, "(")
    .replace(/\s+\)/g, ")")
    .replace(/\s{2,}/g, " ")
    .trim();
}
